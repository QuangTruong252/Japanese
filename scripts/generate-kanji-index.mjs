import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const kanjiDir = path.join(rootDir, 'web/src/data/n5/kanji');
const targetFile = path.join(rootDir, 'web/src/data/n5/kanji-index.ts');

const files = fs.readdirSync(kanjiDir).filter((f) => f.endsWith('.json')).sort();
console.log(`Found ${files.length} kanji files in ${kanjiDir}`);

let out = `// Auto-generated by scripts/generate-kanji-index.mjs - do not edit manually\n`;
out += `import type { KanjiData } from '../../types/lookup.ts';\n\n`;

files.forEach((f, i) => {
  out += `import kanji_${i} from './kanji/${f}' with { type: 'json' };\n`;
});

out += `\nexport const ALL_KANJI: KanjiData[] = [\n`;
files.forEach((_, i) => {
  out += `  kanji_${i} as unknown as KanjiData,\n`;
});
out += `];\n\n`;
out += `export const KANJI_MAP: Map<string, KanjiData> = new Map(\n`;
out += `  ALL_KANJI.map((k) => [k.character, k])\n`;
out += `);\n`;

fs.writeFileSync(targetFile, out, 'utf-8');
console.log(`Wrote ${targetFile} with ${files.length} kanji.`);
